import AppKit
import CryptoKit
import Observation

struct ClipItem: Identifiable, Codable, Equatable {
    enum Content: Codable, Equatable {
        case text(String)
        case image(fileName: String)
        case files([URL])
    }

    let id: UUID
    var content: Content
    /// Empreinte du contenu, pour dédoublonner.
    var hash: String
    var date: Date
    var sourceBundleID: String?
    var pinned = false
}

/// Historique du presse-papier.
///
/// macOS ne notifie pas les changements : on compare `changeCount` deux fois par seconde
/// (coût négligeable). Les copies marquées comme sensibles par les gestionnaires de mots
/// de passe (convention nspasteboard.org) ne sont jamais enregistrées.
@Observable
@MainActor
final class ClipboardController {
    private static let maxUnpinned = 60
    private static let maxTextLength = 20_000

    /// Types posés par les gestionnaires de mots de passe et les copies automatiques.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]
    private static let ignoredApps: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
    ]

    private(set) var items: [ClipItem] = []

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var thumbnails: [UUID: NSImage] = [:]
    private var appIcons: [String: NSImage] = [:]

    private let storeURL: URL
    private let imagesURL: URL

    init() {
        let base = URL.appSupport
        storeURL = base.appendingPathComponent("clipboard.json")
        imagesURL = base.appendingPathComponent("ClipboardImages", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesURL, withIntermediateDirectories: true)

        lastChangeCount = pasteboard.changeCount
        load()

        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    /// Épinglés d'abord, puis du plus récent au plus ancien.
    var sortedItems: [ClipItem] {
        items.filter(\.pinned) + items.filter { !$0.pinned }
    }

    // MARK: - Actions

    /// Remet l'élément dans le presse-papier (prêt pour ⌘V) et le remonte en tête.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let string):
            pasteboard.setString(string, forType: .string)
        case .image:
            if let image = fullImage(for: item) { pasteboard.writeObjects([image]) }
        case .files(let urls):
            pasteboard.writeObjects(urls as [NSURL])
        }
        lastChangeCount = pasteboard.changeCount

        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var updated = items.remove(at: index)
        updated.date = Date()
        items.insert(updated, at: 0)
        save()
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        discardFiles(of: item)
        save()
    }

    /// Vide l'historique, en gardant les éléments épinglés.
    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(discardFiles)
        items.removeAll { !$0.pinned }
        save()
    }

    // MARK: - Affichage

    func thumbnail(for item: ClipItem) -> NSImage? {
        if let cached = thumbnails[item.id] { return cached }
        guard let image = fullImage(for: item) else { return nil }
        let thumb = image.downscaled(maxSide: 320)
        thumbnails[item.id] = thumb
        return thumb
    }

    func appIcon(for bundleID: String?) -> NSImage? {
        guard let bundleID else { return nil }
        if let cached = appIcons[bundleID] { return cached }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        appIcons[bundleID] = icon
        return icon
    }

    private func fullImage(for item: ClipItem) -> NSImage? {
        guard case .image(let fileName) = item.content else { return nil }
        return NSImage(contentsOf: imagesURL.appendingPathComponent(fileName))
    }

    // MARK: - Capture

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, Self.ignoredApps.contains(source) { return }

        guard let (content, hash) = readContent() else { return }

        if let index = items.firstIndex(where: { $0.hash == hash }) {
            // Déjà connu : on le remonte simplement.
            var existing = items.remove(at: index)
            existing.date = Date()
            existing.sourceBundleID = source ?? existing.sourceBundleID
            items.insert(existing, at: 0)
        } else {
            items.insert(ClipItem(id: UUID(), content: content, hash: hash, date: Date(), sourceBundleID: source), at: 0)
            trim()
        }
        save()
    }

    private func readContent() -> (ClipItem.Content, String)? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return (.files(urls), Self.digest(Data(urls.map(\.path).joined(separator: "\n").utf8)))
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let text = String(string.prefix(Self.maxTextLength))
            return (.text(text), Self.digest(Data(text.utf8)))
        }

        if let image = NSImage(pasteboard: pasteboard), let png = image.pngData {
            let hash = Self.digest(png)
            let fileName = "\(hash).png"
            let url = imagesURL.appendingPathComponent(fileName)
            if !FileManager.default.fileExists(atPath: url.path) {
                guard (try? png.write(to: url)) != nil else { return nil }
            }
            return (.image(fileName: fileName), hash)
        }

        return nil
    }

    private func trim() {
        let unpinned = items.filter { !$0.pinned }
        guard unpinned.count > Self.maxUnpinned else { return }
        let overflow = unpinned.suffix(unpinned.count - Self.maxUnpinned)
        let ids = Set(overflow.map(\.id))
        overflow.forEach(discardFiles)
        items.removeAll { ids.contains($0.id) }
    }

    private func discardFiles(of item: ClipItem) {
        thumbnails[item.id] = nil
        if case .image(let fileName) = item.content { removeImageFile(fileName) }
    }

    private func removeImageFile(_ fileName: String) {
        // Un même fichier ne sert qu'à un seul élément (dédoublonnage par empreinte).
        guard !items.contains(where: { $0.content == .image(fileName: fileName) }) else { return }
        try? FileManager.default.removeItem(at: imagesURL.appendingPathComponent(fileName))
    }

    private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - Persistance

    private func load() {
        guard let data = try? Data(contentsOf: storeURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: storeURL, options: .atomic)
    }
}

private extension NSImage {
    var pngData: Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    func downscaled(maxSide: CGFloat) -> NSImage {
        let scale = min(1, maxSide / max(size.width, size.height, 1))
        guard scale < 1 else { return self }
        let target = NSSize(width: size.width * scale, height: size.height * scale)
        return NSImage(size: target, flipped: false) { rect in
            self.draw(in: rect)
            return true
        }
    }
}
